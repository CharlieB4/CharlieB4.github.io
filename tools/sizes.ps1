# Regenerates image-sizes.js (width/height of every project image) so the page can lay
# images out without cropping. Run after adding or replacing images:
#   powershell -ExecutionPolicy Bypass -File tools\sizes.ps1
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
$lines = Get-ChildItem (Join-Path $root "images\projects") -File | Sort-Object Name | ForEach-Object {
  $img = [System.Drawing.Image]::FromFile($_.FullName)
  $line = '  "images/projects/{0}": [{1}, {2}],' -f $_.Name, $img.Width, $img.Height
  $img.Dispose(); $line
}
$js = "// Generated by tools/sizes.ps1 - do not edit by hand.`nconst IMAGE_SIZES = {`n" + ($lines -join "`n") + "`n};`n"
[IO.File]::WriteAllText((Join-Path $root "image-sizes.js"), $js, (New-Object System.Text.UTF8Encoding $false))
"wrote image-sizes.js ($($lines.Count) images)"
